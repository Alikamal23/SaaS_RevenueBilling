document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('.edit-btn').forEach(button => {
        button.addEventListener('click', function () {
            const wrapper = this.closest('.template-wrapper');
            wrapper.querySelector('.view-card').classList.add('d-none');
            wrapper.querySelector('.edit-card').classList.remove('d-none');
        });
    });

    document.querySelectorAll('.close-edit').forEach(button => {
        button.addEventListener('click', function () {
            const wrapper = this.closest('.template-wrapper');
            if (wrapper) {
                wrapper.querySelector('.edit-card').classList.add('d-none');
                wrapper.querySelector('.view-card').classList.remove('d-none');
            }
            document.getElementById('createTemplateCard').classList.add('d-none');
            document.getElementById('pills-tabContent').classList.remove('d-none');
        });
    });

    document.getElementById('addTemplateBtn').addEventListener('click', function () {
        document.getElementById('pills-tabContent').classList.add('d-none');
        document.getElementById('createTemplateCard').classList.remove('d-none');
    });
});


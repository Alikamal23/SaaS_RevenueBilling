document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('.edit-btn').forEach(button => {
        button.addEventListener('click', function () {
            const wrapper = this.closest('.template-wrapper');
            wrapper.querySelector('.view-card').classList.add('d-none');
            wrapper.querySelector('.edit-card').classList.remove('d-none');
        });
    });

    document.querySelectorAll('.close-edit').forEach(button => {
        button.addEventListener('click', function () {
            const wrapper = this.closest('.template-wrapper');
            if (wrapper) {
                wrapper.querySelector('.edit-card').classList.add('d-none');
                wrapper.querySelector('.view-card').classList.remove('d-none');
            }
            document.getElementById('createTemplateCard').classList.add('d-none');
            document.getElementById('pills-tabContent').classList.remove('d-none');
        });
    });

    document.getElementById('addTemplateBtn').addEventListener('click', function () {
        document.getElementById('pills-tabContent').classList.add('d-none');
        document.getElementById('createTemplateCard').classList.remove('d-none');
    });
});

$(document).ready(function () {

    //send_email
    $(document).on("click", ".send-email", function () {
        Swal.fire({
            title: 'Do you want to send a test email?',
            icon: 'question',
            showCancelButton: true,
            confirmButtonText: 'Send Email'
        }).then((r) => {
            if (!r.isConfirmed)
                return;


            var tempbody = `
                    <html>
                    <body style="font-family: Arial, sans-serif; color: #333;">

                        <h2 style="color:#1a73e8;">
                            Revenue & Billing Suite
                        </h2>

                        <p>
                            Dear <strong>{{clientName}}</strong>,
                        </p>

                        <p>
                            We hope you are doing well.
                        </p>

                        <p>
                            This is a notification from the Revenue & Billing Suite.
                            Please review the information provided in this email.
                        </p>

                        <p>
                            This is an automated communication generated by the Revenue & Billing Suite.
                        </p>

                        <p>
                            If you have any questions or require further assistance,
                            please contact our support team.
                        </p>

                        <p>
                            Thank you,<br>
                            <strong style="color:#1a73e8;">
                                Revenue & Billing Team
                            </strong>
                        </p>

                    </body>
                    </html>
            `;

            tempbody = tempbody.replace('{{clientName}}', 'Mettis Global');

            var formData = new FormData();
            formData.append("test_email", $("#test_email_address").val() || "");
            formData.append("template_id", $("#hdnTemplateId").val() || 0);
            formData.append("subject", $("#template_subject").val() || "SaaS Revenue Billing");
            formData.append("body", $("#template_body").val() || tempbody);

            $.ajax({
                url: GetGlobalURL('Base', 'EmailTemplate'),
                type: "POST",
                data: formData,
                processData: false,
                contentType: false,
                success: function (response) {
                    console.log(response);

                    Swal.fire(
                        "Success",
                        "Test email sent successfully.",
                        "success"
                    );
                },
                error: function (xhr) {
                    console.log(xhr);

                    Swal.fire(
                        "Error",
                        xhr.responseText || "Unable to send test email.",
                        "error"
                    );
                }
            });

        });
    });



});
